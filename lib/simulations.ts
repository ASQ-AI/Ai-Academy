/** The scenario list exposed to the browser — the criteria stay server-only. */
export function publicSimulations(): Simulation[] {
  return SIMULATIONS.map(({ criteria, ...s }) => s);
}

/** Looks up a scenario (including its private criteria) by id, server-side only. */
export function findSimulation(id: string): SimulationInternal | null {
  return SIMULATIONS.find((s) => s.id === id) || null;
}
